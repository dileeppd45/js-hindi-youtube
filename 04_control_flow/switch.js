const month  = "apr"
switch (month) {
    case "jan":
        console.log('january')
        break;
    case "feb":
        console.log('february')
        break;
    case "mar":
        console.log('march')
        break;
    case "apr":
        console.log('april')
        break;
    case "may":
        console.log('may')
        break;
    case "jun":
        console.log('june')
        break;

    default:
        console.log('default case match')
        break;
}